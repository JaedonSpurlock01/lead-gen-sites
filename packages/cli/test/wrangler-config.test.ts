import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { loadCloudflareConfig, loadSite } from "@lead-gen/engine/load";
import { afterAll, describe, expect, it } from "vitest";
import { wranglerConfig, writeWranglerConfig } from "../src/wrangler-config";
import { makeFixtureRepo } from "./fixture";

const fixture = makeFixtureRepo();
afterAll(() => fixture.cleanup());

describe("wranglerConfig", () => {
  it("builds the Worker config from site.json and the shared config", () => {
    const ref = { niche: "asphalt-paving", id: "pocatello", nicheDir: join(fixture.root, "niches/asphalt-paving"), siteDir: join(fixture.root, "niches/asphalt-paving/sites/pocatello") };
    const { site } = loadSite(ref.nicheDir, ref.id);
    const config = wranglerConfig({ root: fixture.root, ref, site, cloudflare: loadCloudflareConfig(fixture.root), tracerFormsUrl: "https://tracer.test/api/forms" });
    expect(config).toEqual({
      $schema: "../../../../node_modules/wrangler/config-schema.json",
      name: "asphalt-paving-pocatello",
      compatibility_date: "2026-10-10",
      compatibility_flags: ["nodejs_compat"],
      workers_dev: false,
      preview_urls: false,
      main: "../../../../dist/pocatello/_worker.js/index.js",
      assets: { directory: "../../../../dist/pocatello", binding: "ASSETS" },
      routes: [{ pattern: "pocatelloasphaltpaving.com", custom_domain: true }],
      vars: { TRACER_FORMS_URL: "https://tracer.test/api/forms" },
      secrets_store_secrets: [{ binding: "TRACER_FORM_KEY", store_id: "TODO_SECRETS_STORE_ID", secret_name: "TRACER_FORM_KEY" }],
      observability: { logs: { enabled: true, invocation_logs: true } },
    });
    const path = writeWranglerConfig({ root: fixture.root, ref, site, cloudflare: loadCloudflareConfig(fixture.root), tracerFormsUrl: "https://tracer.test/api/forms" });
    expect(existsSync(path)).toBe(true);
    expect(readFileSync(path, "utf8")).toMatch(/^\/\/ Generated by `pnpm build`/);
  });
});
