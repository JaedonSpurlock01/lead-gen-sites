import { writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import type { CloudflareConfig, ResolvedSite } from "@lead-gen/schema";
import type { SiteRef } from "./targets";

export type WranglerConfigInput = {
  root: string;
  ref: SiteRef;
  site: ResolvedSite;
  cloudflare: CloudflareConfig;
  tracerFormsUrl: string;
};

export const wranglerConfigPath = (ref: SiteRef) => join(ref.siteDir, "wrangler.jsonc");

/**
 * The Worker config for one site, generated from site.json plus the shared config. Keys verified
 * against the Wrangler configuration reference: routes with custom_domain, assets, vars,
 * secrets_store_secrets, observability.
 */
export function wranglerConfig({ root, ref, site, cloudflare, tracerFormsUrl }: WranglerConfigInput) {
  const distDir = join(root, "dist", site.id);
  const rel = (target: string) => relative(ref.siteDir, target).split("\\").join("/");
  return {
    $schema: rel(join(root, "node_modules", "wrangler", "config-schema.json")),
    name: site.cloudflareProject,
    compatibility_date: cloudflare.compatibilityDate,
    compatibility_flags: cloudflare.compatibilityFlags,
    workers_dev: false,
    preview_urls: false,
    main: rel(join(distDir, "_worker.js", "index.js")),
    assets: {
      directory: rel(distDir),
      binding: "ASSETS",
    },
    routes: [{ pattern: site.domain, custom_domain: true }],
    vars: {
      TRACER_FORMS_URL: tracerFormsUrl,
    },
    secrets_store_secrets: [
      {
        binding: cloudflare.secretsStore.binding,
        store_id: cloudflare.secretsStore.storeId,
        secret_name: cloudflare.secretsStore.secretName,
      },
    ],
    observability: {
      logs: {
        enabled: true,
        invocation_logs: true,
      },
    },
  };
}

export function writeWranglerConfig(input: WranglerConfigInput): string {
  const path = wranglerConfigPath(input.ref);
  const header = "// Generated by `pnpm build` from site.json and config/*.json. Do not edit; it is gitignored.\n";
  writeFileSync(path, `${header}${JSON.stringify(wranglerConfig(input), null, 2)}\n`);
  return path;
}
